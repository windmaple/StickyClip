import Cocoa

/// Polls the general pasteboard for changes and feeds new content into the store.
/// (macOS has no clipboard-change notification, so polling `changeCount` is the standard approach.)
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    var isPaused: Bool {
        get { UserDefaults.standard.bool(forKey: "isPaused") }
        set { UserDefaults.standard.set(newValue, forKey: "isPaused") }
    }

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount

    /// Pasteboard markers used by password managers & others to say "don't record me".
    /// See http://nspasteboard.org
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType"
    ]

    private let ignoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop"
    ]

    /// Ignore images larger than this to keep the history light.
    private let maxImageBytes = 25 * 1024 * 1024

    private init() {}

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call right after StickyClip itself writes to the pasteboard so we don't re-record it.
    func ignoreCurrentChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !isPaused else { return }

        let types = (pb.types ?? []).map { $0.rawValue }
        if types.contains(where: { ignoredTypes.contains($0) }) { return }

        let frontApp = NSWorkspace.shared.frontmostApplication
        if let bid = frontApp?.bundleIdentifier, ignoredApps.contains(bid) { return }

        guard let content = capture(from: pb) else { return }
        ClipboardStore.shared.add(content, sourceApp: frontApp)
    }

    private func capture(from pb: NSPasteboard) -> CapturedContent? {
        // 1. Files copied in Finder (these also carry an icon image + name string, so check first).
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }

        let string = pb.string(forType: .string)?
            .trimmingCharacters(in: .newlines)
        let hasText = !(string?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
        let hasImage = pb.availableType(from: [.png, .tiff]) != nil

        // 2. Text wins when both are present (e.g. spreadsheet cells also carry a picture)…
        //    …unless the text is just a URL, as with a browser's "Copy Image" — then keep the picture.
        let textIsJustURL: Bool = {
            guard let s = string?.trimmingCharacters(in: .whitespacesAndNewlines),
                  !s.contains(where: { $0.isWhitespace }),
                  let url = URL(string: s), url.scheme != nil else { return false }
            return true
        }()
        if hasText, let string, !(hasImage && textIsJustURL) {
            return .text(string)
        }

        // 3. Images (screenshots, "Copy Image" in browsers, etc.)
        if hasImage {
            if let png = pb.data(forType: .png), png.count <= maxImageBytes,
               let image = NSImage(data: png) {
                return .image(png, pixelSize(of: image))
            }
            if let tiff = pb.data(forType: .tiff), tiff.count <= maxImageBytes * 2,
               let rep = NSBitmapImageRep(data: tiff),
               let png = rep.representation(using: .png, properties: [:]),
               png.count <= maxImageBytes {
                return .image(png, NSSize(width: rep.pixelsWide, height: rep.pixelsHigh))
            }
        }
        return nil
    }

    private func pixelSize(of image: NSImage) -> NSSize {
        if let rep = image.representations.first, rep.pixelsWide > 0 {
            return NSSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        return image.size
    }
}
